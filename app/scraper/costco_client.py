"""Playwright client that signs in to costco.com and downloads every receipt type through the GraphQL API.

The orders endpoint is protected by the Kasada anti-bot system: every request must carry one-time
x-kpsdk-* headers generated by its script on the page. So requests are sent via XMLHttpRequest
from inside an open costco.com page, where Kasada intercepts the XHR and adds the headers itself.
Direct requests (httpx, fetch) get a 404.
"""
